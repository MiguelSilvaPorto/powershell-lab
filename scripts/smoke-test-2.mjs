for (const test of tests) {
  try {
    const result = executeLine(test, world, { preview: true })
    const stages = result.stages.map((s) => `${s.cmdlet}${s.error ? (s.suppressed ? '~' : '!') : `(${s.outputCount})`}`).join(' -> ')
    let line = `\n$ ${test}\n  ok=${result.ok} [${stages || result.meta.typeName}]`
    if (result.objects.length) line += ` objs=${result.objects.length}`
    if (result.effects.length) line += ` fx=${result.effects.map((e) => e.type).join(',')}`
    if (result.notes.length) line += `\n  note: ${result.notes.join(' | ').slice(0, 200)}`
    if (result.errors.length) line += `\n  ERROR: ${result.errors.map((e) => e.message + (e.hint ? ' // ' + e.hint : '')).join(' || ').slice(0, 260)}`
    if (result.meta.view === 'text') line += `\n  text: ${String(result.meta.text).slice(0, 160).replace(/\n/g, ' / ')}`
    console.log(line)
  } catch (error) {
    console.log(`\n$ ${test}\n  THREW: ${error.stack}`)
  }
}
